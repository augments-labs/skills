"""Hermes Agent plugin entry for this bundle.

Generated by scripts/sync-plugins.sh from scripts/templates/hermes-init.py.
Registers every skills/<name>/SKILL.md, which Hermes exposes as
<plugin>:<name>. It registers skills only: no hooks and no tools.
"""

import json
from pathlib import Path


def _description(text):
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return ""
    for line in lines[1:]:
        if line.strip() == "---":
            break
        if line.startswith("description:"):
            value = line[len("description:"):].strip()
            if len(value) > 1 and value[0] == value[-1] == '"':
                try:
                    return json.loads(value)
                except ValueError:
                    return value[1:-1]
            if len(value) > 1 and value[0] == value[-1] == "'":
                return value[1:-1].replace("''", "'")
            return value
    return ""


def register(ctx):
    root = Path(__file__).resolve().parent / "skills"
    for skill_md in sorted(root.glob("*/SKILL.md")):
        text = skill_md.read_text(encoding="utf-8")
        ctx.register_skill(skill_md.parent.name, skill_md, description=_description(text))
